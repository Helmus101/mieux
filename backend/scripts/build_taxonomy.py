"""Compile the Mieux taxonomy: app/data/taxonomy_base.json + app/data/taxonomy_ext.txt -> app/mieux_taxonomy.json (+ docs/TAXONOMY.md).

    cd backend && .venv/bin/python -m scripts.build_taxonomy

The extension file is the editable source for everything added to the base list (new departments, categories and types).
Fails loudly on an unknown parent, a duplicate type name or a duplicate id, so the taxonomy never silently drifts."""
import json
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE, EXT = os.path.join(HERE, "app", "data", "taxonomy_base.json"), os.path.join(HERE, "app", "data", "taxonomy_ext.txt")
OUT, DOC = os.path.join(HERE, "app", "mieux_taxonomy.json"), os.path.join(HERE, "..", "docs", "TAXONOMY.md")


def slug(s: str) -> str:
    s = unicodedata.normalize("NFKD", s.replace("œ", "oe")).encode("ascii", "ignore").decode().upper()
    return re.sub(r"[^A-Z0-9]+", "_", s).strip("_")


def main() -> None:
    d = json.load(open(BASE, encoding="utf-8"))
    nodes = d["nodes"]
    by = {n["id"]: n for n in nodes}
    dept_of = {n["id"][2:4]: n for n in nodes if n["level"] == 1}
    names = {}
    for n in nodes:
        if n["level"] == 3:
            names.setdefault(n["name_fr"].lower(), []).append(n["id"])
    nxt = max(int(n["id"][1:]) for n in nodes if n["level"] == 3) + 1

    def add(n):
        if n["id"] in by:
            sys.exit(f"duplicate id {n['id']}")
        by[n["id"]] = n
        nodes.append(n)

    for ln, line in enumerate(open(EXT, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        f = line.split("|")
        if f[0] == "D":
            nn, fr, en = f[1], f[2], f[3]
            nid = f"D_{nn}_{slug(fr)}"
            dept_of[nn] = {"id": nid, "name_fr": fr, "name_en": en}
            add({"id": nid, "parent_id": "", "level": 1, "node_type": "department", "name_fr": fr, "name_en": en, "path_fr": fr, "path_en": en,
                 "description_fr": f"Rayon principal : {fr.lower()}.", "examples": "", "substitution_group": "", "comparison_unit": "",
                 "classification_rule": "Classer ici les produits dont la fonction alimentaire principale relève de ce rayon."})
        elif f[0] == "C":
            nn, key, fr, en = f[1], f[2], f[3], f[4]
            dep = dept_of[nn]
            nid = f"C_{dep['id'][2:]}_{key}"
            add({"id": nid, "parent_id": dep["id"], "level": 2, "node_type": "category", "name_fr": fr, "name_en": en,
                 "path_fr": f"{dep['name_fr']} > {fr}", "path_en": f"{dep['name_en']} > {en}", "description_fr": f"Sous-catégorie de {dep['name_fr'].lower()}.",
                 "examples": "", "substitution_group": "", "comparison_unit": "", "classification_rule": f"Choisir cette catégorie pour les produits correspondant à : {fr.lower()}."})
        elif f[0] == "T":
            cat = by.get("C_" + f[1])
            if not cat:
                sys.exit(f"line {ln}: unknown category C_{f[1]}")
            fr, en, unit = f[2], f[3], f[4]
            if fr.lower() in names:
                sys.exit(f"line {ln}: duplicate type name {fr!r}")
            nid = f"P{nxt:04d}"
            nxt += 1
            names[fr.lower()] = [nid]
            add({"id": nid, "parent_id": cat["id"], "level": 3, "node_type": "product_type", "name_fr": fr, "name_en": en,
                 "path_fr": f"{cat['path_fr']} > {fr}", "path_en": f"{cat['path_en']} > {en}", "description_fr": f"Type de produit : {fr.lower()}.", "examples": fr,
                 "substitution_group": "SG_" + cat["id"][2:], "comparison_unit": unit,
                 "classification_rule": f"Attribuer ce type si le produit est principalement un(e) {fr.lower()}. Ne pas déduire la marque, la recette, le parfum ou le format à partir du seul nom."})
        else:
            sys.exit(f"line {ln}: bad record")
    d["version"] = "2.0"
    d["scope"] = "Food, drink and the non-food items sold alongside them in French and US supermarkets"
    d["product_type_count"] = sum(1 for n in nodes if n["level"] == 3)
    d["total_node_count"] = len(nodes)
    json.dump(d, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    # human-readable listing
    kids = {}
    for n in nodes:
        kids.setdefault(n["parent_id"], []).append(n)
    out = ["# Mieux food taxonomy", "", f"{d['product_type_count']} product types in {sum(1 for n in nodes if n['level']==2)} categories in {sum(1 for n in nodes if n['level']==1)} departments. Generated by `backend/scripts/build_taxonomy.py`; do not edit by hand.", ""]
    for dep in kids[""]:
        out += [f"## {dep['name_fr']} / {dep['name_en']}", ""]
        for cat in kids.get(dep["id"], []):
            out.append(f"### {cat['name_fr']}")
            out.append("")
            out.append("; ".join(t["name_fr"] for t in kids.get(cat["id"], [])))
            out.append("")
    os.makedirs(os.path.dirname(DOC), exist_ok=True)
    open(DOC, "w", encoding="utf-8").write("\n".join(out))
    print(d["product_type_count"], "types,", d["total_node_count"], "nodes")


if __name__ == "__main__":
    main()
